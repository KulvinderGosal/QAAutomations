function tests(taskId: string, spec: [string, string, string][], failAt?: number): TestCase[] {
  return spec.map(([name, file, phase], i) => {
    const status = failAt === undefined ? "queued" : i < failAt ? "passed" : i === failAt ? "failed" : "blocked";
    const history: ("pass" | "fail")[] = Array.from({ length: 10 }, (_, h) =>
      failAt !== undefined && i === failAt && h > 6 ? "fail" : Math.random() > 0.12 ? "pass" : "fail",
    );
    const t: TestCase = {
      id: `${taskId}-t${i}`,
      name,
      file,
      phase: phase as TestCase["phase"],
      status,
      history,
    };
    if (status === "failed") {
      t.error = {
        matcher: "toBeVisible",
        message: `Timed out 5000ms waiting for expect(locator).toBeVisible()`,
        locator: `getByTestId('${name.toLowerCase().replace(/\s+/g, "-")}')`,
        expected: "visible",
        received: "hidden",
        stack: `at ${file}:${24 + i}:9\n    at TestRunner.run (runner.ts:118:5)`,
      };
    }
    return t;
  });
}

